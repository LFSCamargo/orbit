/** Vite packages the same checked-in artwork as Tauri, with no runtime network. */
const assets = import.meta.glob<string>(
  '../../src-tauri/assets/bundled-themes/*/*.{png,webp,jpg}',
  { eager: true, query: '?url', import: 'default' },
)

export function localThemeArtwork(themeId: string, slot: string): string | null {
  if (!/^[a-z0-9-]+$/.test(themeId) || !['logo', 'hero'].includes(slot)) return null
  for (const extension of ['webp', 'png', 'jpg']) {
    const asset =
      assets[`../../src-tauri/assets/bundled-themes/${themeId}/${slot}.${extension}`]
    if (asset) return new URL(asset, window.location.href).href
  }
  return null
}

/** Card-sized images generated by the native GPU pipeline at asset preparation time. */
export function localThemePreview(themeId: string, slot: 'logo' | 'hero'): string | null {
  return packagedThemePreview(themeId, slot) ?? localThemeArtwork(themeId, slot)
}

/** Only precomputed thumbnails qualify for skipping native preparation. */
export function packagedThemePreview(
  themeId: string,
  slot: 'logo' | 'hero',
): string | null {
  if (!/^[a-z0-9-]+$/.test(themeId)) return null
  const file = `preview-${slot}.webp`
  const asset = assets[`../../src-tauri/assets/bundled-themes/${themeId}/${file}`]
  return asset ? new URL(asset, window.location.href).href : null
}
